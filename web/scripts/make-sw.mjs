// Writes dist/sw.js: the service worker that lets the website open with no connection. It keeps the app
// itself (the page, scripts, styles, map style, icons) and nothing else: trail files and map tiles are kept
// by the app in its own storage. Each build gets its own cache, named by a hash of the files, so a new
// version replaces the old one the next time the site is opened.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const dist = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist');
const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name), rel = relative(dist, path).split('\\').join('/');
    if (statSync(path).isDirectory()) { if (rel !== 'data') walk(path); } else if (rel !== 'sw.js' && !rel.endsWith('.map')) files.push(rel);
  }
};
walk(dist);
files.sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(dist, f)));
const version = hash.digest('hex').slice(0, 12);

writeFileSync(join(dist, 'sw.js'), `// Generated by scripts/make-sw.mjs. Do not edit.
const CACHE = 'switchback-shell-${version}';
const FILES = ${JSON.stringify(['./', ...files.filter((f) => f !== 'index.html')])};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('switchback-shell-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // only the app's own files; trail data (data/) and everything from other sites go straight to the network
  if (url.origin !== location.origin || !url.pathname.startsWith(new URL('./', location.href).pathname)) return;
  const rel = url.pathname.slice(new URL('./', location.href).pathname.length);
  if (rel.startsWith('data/') || rel === 'sw.js') return;
  event.respondWith(
    caches.open(CACHE).then(async (cache) => {
      const hit = await cache.match(req.mode === 'navigate' ? './' : req, { ignoreSearch: true, ignoreVary: true });
      if (hit) return hit;
      return fetch(req);
    }),
  );
});
`);
console.log(`sw.js: ${files.length} files, version ${version}`);
